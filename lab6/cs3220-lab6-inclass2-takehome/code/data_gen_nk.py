"""
Checker for N < K cases (Take-Home Part B).

When N < K, each row of the array produces only N results every K cycles, so a correct design
has gaps (zeros) between results on row_data_out. This checker removes those gaps from each
array row separately, then compares the remaining values, in order, with the expected results.

Data is generated by data_gen.py (same as for every other test). Only verification differs.
Zeros are removed from the expected values too, so a real result that wraps to 0 cannot cause
a false failure.
"""
import numpy


def squeeze(values):
    return [int(v) for v in values if v != 0]


def contains_in_order(stream, expected):
    """True if `expected` appears as one contiguous block inside `stream`."""
    n = len(expected)
    if n == 0:
        return True
    for start in range(len(stream) - n + 1):
        if stream[start:start + n] == expected:
            return True
    return False


def verify_squeezed(rows, cols, num_tests,
                    expected_file="d_matrix.bin", result_file="results.bin"):
    expected = numpy.fromfile(expected_file, dtype=numpy.uint8).reshape(-1, rows)   # one column of C per line
    result = numpy.fromfile(result_file, dtype=numpy.uint8).reshape(-1, rows)       # row_data_out, every cycle

    numpy.set_printoptions(threshold=numpy.inf, linewidth=numpy.inf)
    ok = True
    for i in range(rows):
        exp_i = squeeze(expected[:, i])
        res_i = squeeze(result[:, i])
        row_ok = contains_in_order(res_i, exp_i)
        print(f"Row {i}: expected {len(exp_i)} nonzero values, got {len(res_i)} -> {'match' if row_ok else 'MISMATCH'}")
        if not row_ok:
            print(f"  Expected (gaps removed): {exp_i[:40]}{' ...' if len(exp_i) > 40 else ''}")
            print(f"  Result   (gaps removed): {res_i[:40]}{' ...' if len(res_i) > 40 else ''}")
        ok = ok and row_ok
    return ok


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument("--a-size", type=str, default="4x4", help="Matrix A dimensions (M x K)")
    parser.add_argument("--b-size", type=str, default="4x4", help="Matrix B dimensions (K x N)")
    parser.add_argument("--c-size", type=str, default="4x4", help="Matrix C dimensions (M x N)")
    parser.add_argument("--num-tests", type=int, default=1, help="Number of matrix multiplications")
    args = parser.parse_args()

    rows, cols = (int(x) for x in args.c_size.split("x"))
    if verify_squeezed(rows, cols, args.num_tests):
        print("PASSED!")
    else:
        print("FAILED!")
